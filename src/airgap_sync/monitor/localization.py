def zh(value):
    """Translate known labels; preserve arbitrary identifiers and diagnostic text."""
    if not isinstance(value, str):
        return value
    if value in LABELS:
        return LABELS[value]
    for pattern, prefix in (
        (r"(FAILED|MISMATCH) runs: (\d+)", "任务数"),
        (r"Cleanup pending: (\d+)", "待清理任务数"),
    ):
        if match := re.fullmatch(pattern, value):
            if len(match.groups()) == 2:
                return f"{zh(match[1])}{prefix}：{match[2]}"
            return f"{prefix}：{match[1]}"
    if match := re.fullmatch(r"Known (FAILED|MISMATCH) run: (.+)", value):
        return f"已知{zh(match[1])}任务：{match[2]}"
    if match := re.fullmatch(r"Source (cycle|run) reports (\w+)", value):
        kind = "同步周期" if match[1] == "cycle" else "任务"
        return f"源端{kind}状态：{zh(match[2])}"
    if match := re.fullmatch(r"Latest Destination run is (\w+)", value):
        return f"目标端最新任务状态：{zh(match[1])}"
    if match := re.fullmatch(r"(\d+)d (\d+)h", value):
        return f"{match[1]} 天 {match[2]} 小时"
    if match := re.fullmatch(r"(\d+)h (\d+)m", value):
        return f"{match[1]} 小时 {match[2]} 分钟"
    return re.sub(r"^(\d+) days?, ", r"\1 天 ", value)
